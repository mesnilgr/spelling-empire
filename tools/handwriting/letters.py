"""Stroke templates for handwritten letters (capitals, print lowercase, French cursive lowercase).

Coordinates are in a unit box, y pointing down. Each letter maps to a list of variants;
each variant is a list of strokes; each stroke is a list of (x, y) points.
"""
import math


def arc(cx, cy, rx, ry, a0, a1, n=16):
    """Points on an ellipse from angle a0 to a1 (degrees, y down so negative angles go up)."""
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def line(*pts):
    return list(pts)


def bump(x0, y0, y1, w, n=10):
    """Right-hand bowl from (x0, y0) to (x0, y1), as in B, D, P, R."""
    r = (y1 - y0) / 2
    pts = [(x0, y0), (x0 + w - r * 0.9, y0)]
    pts += arc(x0 + w - r * 0.9, y0 + r, r * 0.9, r, -90, 90, n)[1:]
    pts += [(x0, y1)]
    return pts


